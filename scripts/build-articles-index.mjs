// Regenerates src/lib/articles-index.ts from the frontmatter in src/content/articles/*.md.
// Run: node scripts/build-articles-index.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "src/content/articles";
const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();

function fm(raw) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  const data = {};
  if (!m) return { data, body: raw };
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].replace(/\s+#.*$/, "").trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1).replace(/\\"/g, '"');
    data[kv[1]] = v;
  }
  return { data, body: m[2] };
}

function topicFor(t) {
  const s = t.toLowerCase();
  if (/strava|garmin|whoop|apple watch|mapmyrun|shoe|sock|headphone|bottle/.test(s)) return "training";
  if (/race|5k|10k|half marathon|marathon/.test(s)) return "racing";
  if (/rain|cold|tights|night|safety|weather/.test(s)) return "safety";
  if (/eat|fuel|recovery|compression|water bottle|hydrat/.test(s)) return "fuel";
  if (/club|group|partner|community|pittsburgh|near me|gym/.test(s)) return "community";
  if (/beginner|first|couch|start/.test(s)) return "first-run";
  return "training";
}

const entries = files.map((f) => {
  const { data, body } = fm(readFileSync(join(dir, f), "utf8"));
  const slug = f.replace(/\.md$/, "");
  if (data.slug && data.slug !== slug) throw new Error(`${f}: slug ${data.slug} does not match filename`);
  const words = body.split(/\s+/).filter(Boolean).length;
  return {
    slug,
    title: data.title,
    description: data.description,
    topic: data.topic || topicFor(data.title),
    minutes: Math.max(3, Math.round(words / 230)),
    updated: data.updated || "2026-10-29",
    published: data.published || data.updated || "2026-10-29",
  };
});

for (const e of entries) {
  if (!e.title || !e.description) throw new Error(`${e.slug}: missing title/description`);
}

const out = `// Generated by scripts/build-articles-index.mjs. Do not edit by hand.
import type { Topic } from "@/lib/library";

export type ArticleMeta = {
  slug: string;
  title: string;
  description: string;
  topic: Topic;
  minutes: number;
  updated: string;
  published: string;
};

export const ARTICLES: ArticleMeta[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync("src/lib/articles-index.ts", out);
console.log(`wrote ${entries.length} articles`);
